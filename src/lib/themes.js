export const MODES = [
  { value: 'light', label: 'Light' },
  { value: 'dark', label: 'Dark' },
  { value: 'system', label: 'System' },
];

/** 'light' | 'dark' | 'system' -> 'light' | 'dark' */
export const resolveMode = (mode, systemDark = false) => (mode === 'system' || !mode ? (systemDark ? 'dark' : 'light') : mode);

/** The full colour set for a palette in a given mode. */
export function themeOf(key, mode, systemDark = false) {
  const p = PALETTES.find((x) => x.key === key) ?? PALETTES[0];
  const m = resolveMode(mode, systemDark);
  return { ...(m === 'dark' ? p.dark : p.light), key: p.key, name: p.name, dark: m === 'dark' };
}

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());

/** Writes the palette to CSS variables on <html>. */
export function applyTheme(key, mode, systemDark = false) {
  const t = themeOf(key, mode, systemDark);
  const root = document.documentElement;
  for (const [k, v] of Object.entries(t)) {
    if (typeof v === 'string' && v.startsWith('#')) root.style.setProperty('--' + kebab(k), v);
  }
  root.style.colorScheme = t.dark ? 'dark' : 'light';
}
